const AES_RCON: [u8; 11] = [
    0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36,
];

fn expand_key(key: &[u8; 16]) -> [u8; 176] {
    let mut words = [0u8; 176];
    words[..16].copy_from_slice(key);
    for index in 4..44 {
        let mut temp = [
            words[(index - 1) * 4],
            words[(index - 1) * 4 + 1],
            words[(index - 1) * 4 + 2],
            words[(index - 1) * 4 + 3],
        ];
        if index % 4 == 0 {
            temp.rotate_left(1);
            for byte in &mut temp {
                *byte = AES_SBOX[*byte as usize];
            }
            temp[0] ^= AES_RCON[index / 4];
        }
        for offset in 0..4 {
            words[index * 4 + offset] = words[(index - 4) * 4 + offset] ^ temp[offset];
        }
    }
    words
}

fn add_round_key(state: &mut [u8; 16], round_key: &[u8]) {
    for (byte, key_byte) in state.iter_mut().zip(round_key.iter()) {
        *byte ^= *key_byte;
    }
}

fn sub_bytes(state: &mut [u8; 16]) {
    for byte in state.iter_mut() {
        *byte = AES_SBOX[*byte as usize];
    }
}

fn shift_rows(state: &mut [u8; 16]) {
    let original = *state;
    for row in 0..4 {
        for column in 0..4 {
            state[4 * column + row] = original[4 * ((column + row) % 4) + row];
        }
    }
}

fn xtime(value: u8) -> u8 {
    (value << 1) ^ if value & 0x80 != 0 { 0x1b } else { 0 }
}

fn mix_columns(state: &mut [u8; 16]) {
    for column in 0..4 {
        let offset = 4 * column;
        let a0 = state[offset];
        let a1 = state[offset + 1];
        let a2 = state[offset + 2];
        let a3 = state[offset + 3];
        let all = a0 ^ a1 ^ a2 ^ a3;
        state[offset] = a0 ^ all ^ xtime(a0 ^ a1);
        state[offset + 1] = a1 ^ all ^ xtime(a1 ^ a2);
        state[offset + 2] = a2 ^ all ^ xtime(a2 ^ a3);
        state[offset + 3] = a3 ^ all ^ xtime(a3 ^ a0);
    }
}

pub fn aes128_encrypt_block(block: &mut [u8; 16], key: &[u8; 16]) {
    let round_keys = expand_key(key);
    add_round_key(block, &round_keys[..16]);
    for round in 1..10 {
        sub_bytes(block);
        shift_rows(block);
        mix_columns(block);
        add_round_key(block, &round_keys[round * 16..round * 16 + 16]);
    }
    sub_bytes(block);
    shift_rows(block);
    add_round_key(block, &round_keys[160..176]);
}

/// AES-128-CBC com padding de zeros (não PKCS#7), como o DuckStation.
pub fn aes128_cbc_encrypt_zero_padded(key: &[u8; 16], iv: &[u8; 16], data: &[u8]) -> Vec<u8> {
    if data.is_empty() {
        return Vec::new();
    }
    let mut padded = data.to_vec();
    let padding = (16 - padded.len() % 16) % 16;
    padded.resize(padded.len() + padding, 0);
    let mut previous = *iv;
    let mut output = Vec::with_capacity(padded.len());
    for offset in (0..padded.len()).step_by(16) {
        let chunk = &padded[offset..offset + 16];
        let mut block = [0u8; 16];
        for index in 0..16 {
            block[index] = chunk[index] ^ previous[index];
        }
        aes128_encrypt_block(&mut block, key);
        output.extend_from_slice(&block);
        previous = block;
    }
    output
}

const BASE64_ALPHABET: &[u8; 64] =
    b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";

pub fn base64_encode(data: &[u8]) -> String {
    let mut output = String::with_capacity(data.len().div_ceil(3) * 4);
    for chunk in data.chunks(3) {
        let b0 = chunk[0] as u32;
        let b1 = chunk.get(1).copied().unwrap_or(0) as u32;
        let b2 = chunk.get(2).copied().unwrap_or(0) as u32;
        let triple = (b0 << 16) | (b1 << 8) | b2;
        output.push(BASE64_ALPHABET[(triple >> 18) as usize & 0x3f] as char);
        output.push(BASE64_ALPHABET[(triple >> 12) as usize & 0x3f] as char);
        if chunk.len() > 1 {
            output.push(BASE64_ALPHABET[(triple >> 6) as usize & 0x3f] as char);
        } else {
            output.push('=');
        }
        if chunk.len() > 2 {
            output.push(BASE64_ALPHABET[triple as usize & 0x3f] as char);
        } else {
            output.push('=');
        }
    }
    output
}

#[cfg(test)]
pub fn hex(data: &[u8]) -> String {
    let mut output = String::with_capacity(data.len() * 2);
    for byte in data {
        output.push_str(&format!("{byte:02x}"));
    }
    output
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sha256_vetores_fips() {
        assert_eq!(
            hex(&sha256(b"")),
            "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"
        );
        assert_eq!(
            hex(&sha256(b"abc")),
            "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
        );
        assert_eq!(
            hex(&sha256(
                b"abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq"
            )),
            "248d6a61d20638b8e5c026930c3e6039a33ce45964ff2167f6ecedd419db06c1"
        );
    }

    #[test]
    fn aes128_vetor_fips_e_cbc_nist() {
        let key: [u8; 16] = [
            0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d,
            0x0e, 0x0f,
        ];
        let mut block: [u8; 16] = [
            0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd,
            0xee, 0xff,
        ];
        aes128_encrypt_block(&mut block, &key);
        assert_eq!(hex(&block), "69c4e0d86a7b0430d8cdb78070b4c55a");

        let cbc_key: [u8; 16] = [
            0x2b, 0x7e, 0x15, 0x16, 0x28, 0xae, 0xd2, 0xa6, 0xab, 0xf7, 0x15, 0x88, 0x09, 0xcf,
            0x4f, 0x3c,
        ];
        let iv: [u8; 16] = [
            0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d,
            0x0e, 0x0f,
        ];
        let plaintext = [
            0x6b, 0xc1, 0xbe, 0xe2, 0x2e, 0x40, 0x9f, 0x96, 0xe9, 0x3d, 0x7e, 0x11, 0x73, 0x93,
            0x17, 0x2a,
        ];
        assert_eq!(
            hex(&aes128_cbc_encrypt_zero_padded(&cbc_key, &iv, &plaintext)),
            "7649abac8119b246cee98e9b12e9197d"
        );
    }

    #[test]
    fn base64_vetores_rfc() {
        assert_eq!(base64_encode(b""), "");
        assert_eq!(base64_encode(b"f"), "Zg==");
        assert_eq!(base64_encode(b"fo"), "Zm8=");
        assert_eq!(base64_encode(b"foo"), "Zm9v");
        assert_eq!(base64_encode(b"foob"), "Zm9vYg==");
        assert_eq!(base64_encode(b"fooba"), "Zm9vYmE=");
        assert_eq!(base64_encode(b"foobar"), "Zm9vYmFy");
    }
}
