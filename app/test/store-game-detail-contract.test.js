"use strict"

const test = require("node:test")
const assert = require("node:assert/strict")
const fs = require("node:fs")
const path = require("node:path")

const root = path.resolve(__dirname, "..")
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), "utf8")

test("detalhe substitui o catálogo da loja em vez de renderizar depois dele", () => {
  const store = read("src", "components", "desktop", "StoreView.tsx")
  const early = store.lastIndexOf("if (pagina) {")
  const catalog = store.lastIndexOf("if (aba === \"retro\")")
  assert.ok(early >= 0 && early < catalog, "detalhe precisa retornar antes do catálogo")
  assert.doesNotMatch(store.slice(catalog), /\{pagina &&/)
})

test("detalhe da biblioteca substitui a grade em vez de sobrepor", () => {
  const library = read("src", "components", "desktop", "LibraryView.tsx")
  const page = library.indexOf("if (paginaLoja) {")
  const grid = library.indexOf("return (\n    <div className=\"flex h-full flex-col\">")
  assert.ok(page >= 0 && page < grid, "página Steam precisa retornar antes da grade")
  assert.match(library, /if \(pagina\) \{/)
  assert.doesNotMatch(library.slice(grid), /\{paginaLoja &&|\{pagina &&/)
})

test("detalhe usa notícias Steam específicas do appid", () => {
  const detail = read("src", "components", "desktop", "ArcadiaStoreGameDetail.tsx")
  const preload = read("electron", "preload.js")
  const main = read("electron", "main.js")
  const types = read("src", "global.d.ts")
  assert.match(detail, /getGameNews\(appid\)/)
  assert.doesNotMatch(detail, /getNews\(\)/)
  assert.match(preload, /getGameNews:.*news:game/)
  assert.match(main, /ipcMain\.handle\("news:game"/)
  assert.match(main, /ISteamNews\/GetNewsForApp\/v2/)
  assert.match(main, /resolveSteamNewsImage\(item\)/)
  assert.match(types, /getGameNews:/)
})

