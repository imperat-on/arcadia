test("trailer da loja abre um player real com fallback HLS", () => {
  const detail = read("src", "components", "desktop", "ArcadiaStoreGameDetail.tsx")
  const main = read("electron", "main.js")
  assert.match(detail, /import Hls from "hls\.js"/)
  assert.match(detail, /<video ref=\{videoRef\}[^>]*controls autoPlay muted playsInline/)
  assert.match(detail, /const \[selectedMovie, setSelectedMovie\] = useState<Movie \| null>\(null\)/)
  assert.match(detail, /setSelectedMovie\(null\)/)
  assert.match(detail, /thumbs\[0\]\?\.movie && <button onClick=\{\(\) => selectMedia\(thumbs\[0\]\)\}/)
  assert.doesNotMatch(detail, /const firstMovie = info\?\.movies\?\.find/)
  assert.doesNotMatch(detail, /setSelectedMovie\(firstMovie \|\| null\)/)
  assert.match(detail, /video\.play\(\)\.catch/)
  assert.match(detail, /preload="auto"/)
  assert.match(detail, /hls\.loadSource\(selectedMovie\.hls\)/)
  assert.match(detail, /item\.mp4 \|\| item\.webm \|\| item\.hls/)
  assert.match(main, /Array\.isArray\(cached\?\.movies\)/)
  assert.doesNotMatch(detail, /movie: true/)
})

