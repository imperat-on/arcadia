test("detalhe Retro preserva a mesma composição visual do detalhe normal", () => {
  const detail = read("src", "components", "desktop", "ArcadiaStoreGameDetail.tsx")
  const retroAchievements = read("src", "components", "desktop", "RetroAchievementsGamePanel.tsx")
  const retroBranch = detail.indexOf("{retro ? (")
  const achievements = detail.indexOf("<RetroAchievementsGamePanel", retroBranch)
  const description = detail.indexOf('title="Descrição"', retroBranch)

  assert.ok(retroBranch >= 0 && achievements > retroBranch && description > achievements)
  assert.match(detail, /isRetro \? \(\s*<img[^>]*object-contain/)
  assert.doesNotMatch(detail, /!retro && <DetailPanel title="Amigos que jogam"/)
  assert.match(retroAchievements, /compact = false/)
  assert.match(retroAchievements, /detail-achievement-grid grid max-h-\[210px\].*overflow-y-auto/)
  assert.match(retroAchievements, /allOpen && items\?\.length && <AchievementsFullScreen/)
  assert.match(retroAchievements, /items\.slice\(0, 6\)/)
  assert.match(retroAchievements, /detail-achievements-all/)
  assert.match(retroAchievements, /h-\[286px\] overflow-hidden/)
})
