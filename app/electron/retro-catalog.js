const CACHE_FILE_NAME = "retro-catalog.json"
const CACHE_VERSION = 1
const CACHE_TTL_MS = 24 * 60 * 60 * 1000
const MAX_SOURCES = 100
const MAX_GAMES = 50000
const MAX_URIS = 16
const MAX_TITLE = 300
const MAX_DESCRIPTION = 2400
const MAX_LIMIT = 48
const MAX_QUERY = 120
const ID_RE = /^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$/

function safePublicUrl(value, maxLength = 2048) {
  if (typeof value !== "string" || !value.trim() || value.length > maxLength) return ""
  try {
    const u = new URL(value.trim())
    if (u.hash) return ""
    if (u.protocol !== "https:" || u.username || u.password || (u.port && u.port !== "443"))
      return ""
    const host = u.hostname.toLowerCase()
    if (
      host === "localhost" ||
      host === "127.0.0.1" ||
      host === "::1" ||
      host.startsWith("[") ||
      host.includes(":") ||
      /^(10|127)\./.test(host) ||
      /^192\.168\./.test(host) ||
      /^172\.(1[6-9]|2\d|3[0-1])\./.test(host)
    )
      return ""
    return u.toString()
  } catch {
    return ""
  }
}

function sourceId(value) {
  const id = String(value ?? "").trim()
  return ID_RE.test(id) || /^\d{1,12}$/.test(id) ? id : ""
}

function cleanText(value, max = MAX_DESCRIPTION) {
  let text = String(value || "")
    .replace(/<br\s*\/?>(?=\s*)/gi, "\n")
    .replace(/<[^>]*>/g, " ")
    .replace(/&nbsp;/gi, " ")
    .replace(/&amp;/gi, "&")
    .replace(/&quot;/gi, '"')
    .replace(/&#39;|&apos;/gi, "'")
    .replace(/&lt;/gi, "<")
    .replace(/&gt;/gi, ">")
    // Hydra feeds are not always generated by the same JSON writer. Decode
    // numeric entities as well, otherwise a title such as `Pokémon &#64;` can
    // never match the metadata provider's spelling.
    .replace(/&#(x[0-9a-f]+|\d+);/gi, (_match, code) => {
      const parsed = /^x/i.test(code) ? parseInt(code.slice(1), 16) : parseInt(code, 10)
      return Number.isFinite(parsed) && parsed >= 0 && parsed <= 0x10ffff
        ? String.fromCodePoint(parsed)
        : " "
    })
    .replace(/[\u0000-\u001f\u007f]/g, " ")
    .replace(/\s+/g, " ")
    .trim()
  return text.slice(0, max)
}

// Hydra's download title is often a ROM filename rather than the name a user
// would put in a library: `[PSX-PS3] Game [PKG] [USA / RUS]`, for example.
// Keep meaningful edition text in the title, but remove dump/region/format
// annotations so searches and cover providers receive a useful query.
